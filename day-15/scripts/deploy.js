"use strict";
/**
 * Deploy CertificateRegistry and tell the frontend where it lives.
 *
 *   npx hardhat run scripts/deploy.js --network localhost   (after `npm run node`)
 *   npx hardhat run scripts/deploy.js --network sepolia     (needs .env, see .env.example)
 *
 * The deployer becomes admin. On the LOCAL chain it is also made an issuer so the
 * demo page works straight away; on Sepolia, grant ISSUER_ROLE deliberately afterwards.
 *
 * Writes frontend/config.js: the ABI + one address per chain id. Only PUBLIC data
 * goes there — the frontend is a public website.
 */
const fs = require("node:fs");
const path = require("node:path");
const hre = require("hardhat");
const { copyLib } = require("./build-web");

const CONFIG_PATH = path.join(__dirname, "..", "frontend", "config.js");
const CHAINS = {
  // rpc: used by the page for FREE read-only checks when no wallet is connected.
  31337: { name: "Hardhat local", explorer: null, rpc: "http://127.0.0.1:8545" },
  11155111: { name: "Sepolia testnet", explorer: "https://sepolia.etherscan.io", rpc: null },
};

/**
 * Read the existing config so other chains' addresses are kept.
 * A missing file is fine (first deploy). A file that EXISTS but can't be parsed
 * is an error: silently starting fresh would erase e.g. the Sepolia address
 * (QA finding L2).
 */
function readConfig(file = CONFIG_PATH) {
  if (!fs.existsSync(file)) return { deployments: {} };
  const src = fs.readFileSync(file, "utf8");
  try {
    const cfg = JSON.parse(src.slice(src.indexOf("{"), src.lastIndexOf("}") + 1));
    if (!cfg || typeof cfg.deployments !== "object") throw new Error("no deployments");
    return cfg;
  } catch (e) {
    throw new Error(`${path.basename(file)} exists but is not valid (${e.message}). Fix or delete it; refusing to overwrite.`);
  }
}

function writeConfig(cfg, file = CONFIG_PATH) {
  const body = JSON.stringify(cfg, null, 2);
  fs.writeFileSync(
    file,
    `// Generated by scripts/deploy.js — do not edit by hand. Public data only.\nwindow.DAPP_CONFIG = ${body};\n`
  );
}

async function main({ file = CONFIG_PATH, allowEphemeral = false } = {}) {
  // `hardhat run` without --network uses an in-memory chain that disappears when
  // the script ends. Writing its address into the frontend config would point the
  // dApp at a contract that no longer exists (QA finding L3).
  if (hre.network.name === "hardhat" && !allowEphemeral) {
    throw new Error("Refusing to deploy to the temporary in-memory chain. Use --network localhost (after `npm run node`) or --network sepolia.");
  }
  const { chainId } = await hre.ethers.provider.getNetwork();
  const id = Number(chainId);
  const [deployer] = await hre.ethers.getSigners();
  if (!deployer) throw new Error("No deployer account. For Sepolia, fill in .env (see .env.example).");

  const balance = await hre.ethers.provider.getBalance(deployer.address);
  console.log(`network : ${hre.network.name} (chain ${id})`);
  console.log(`deployer: ${deployer.address}  balance ${hre.ethers.formatEther(balance)} ETH`);
  if (balance === 0n) throw new Error("Deployer has 0 ETH — get Sepolia test ETH from a faucet first.");

  const reg = await hre.ethers.deployContract("CertificateRegistry", [deployer.address]);
  const receipt = await reg.deploymentTransaction().wait(id === 31337 ? 1 : 2);
  const address = await reg.getAddress();
  console.log(`Registry: ${address}  (block ${receipt.blockNumber}, gas ${receipt.gasUsed})`);
  if (id === 31337) {
    await (await reg.grantRole(await reg.ISSUER_ROLE(), deployer.address)).wait();
    console.log(`issuer  : ${deployer.address} (local demo only)`);
  }

  const artifact = await hre.artifacts.readArtifact("CertificateRegistry");
  const cfg = readConfig(file);
  cfg.abi = artifact.abi;
  cfg.deployments = cfg.deployments || {};
  cfg.deployments[id] = {
    address,
    name: (CHAINS[id] && CHAINS[id].name) || hre.network.name,
    explorer: (CHAINS[id] && CHAINS[id].explorer) || null,
    deployBlock: receipt.blockNumber,
    rpc: (CHAINS[id] && CHAINS[id].rpc) || null,
  };
  writeConfig(cfg, file);
  copyLib();
  console.log(`wrote   : ${path.relative(process.cwd(), file)}`);
  if (CHAINS[id] && CHAINS[id].explorer) console.log(`explorer: ${CHAINS[id].explorer}/address/${address}`);
  return { address, chainId: id };
}

if (require.main === module) {
  main().catch((e) => {
    console.error(e.message || e);
    process.exitCode = 1;
  });
}

module.exports = { main, readConfig, writeConfig, CONFIG_PATH };
