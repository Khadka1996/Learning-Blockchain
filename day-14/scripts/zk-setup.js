"use strict";
// One-off "trusted setup" for both circuits (run: npm run zk:setup).
//
//   circuit.circom ──circom2──▶ circuit.r1cs + circuit.wasm
//   powers of tau (phase 1, any circuit)  ─┐
//   circuit-specific setup (phase 2)  ─────┴─▶ circuit.zkey (proving key) + vkey.json
//   vkey ──snarkjs──▶ contracts/verifiers/<Name>Verifier.sol (verifies proofs on-chain)
//
// WARNING: this is a ONE-PERSON ceremony, fine for learning only. Whoever knows the random
// "toxic waste" of a Groth16 setup can forge proofs. Real projects use a multi-party ceremony
// (e.g. the Hermez / Perpetual Powers of Tau) where ONE honest participant is enough.
const { execFileSync } = require("node:child_process");
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const snarkjs = require("snarkjs");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "zk");
const CIRCUITS = [
  { file: "secret", contract: "SecretVerifier" },
  { file: "secret_naive", contract: "NaiveSecretVerifier" },
];
const entropy = () => crypto.randomBytes(32).toString("hex");

async function main() {
  fs.mkdirSync(OUT, { recursive: true });

  // Phase 1: powers of tau. 2^10 = 1024 constraints is plenty (our circuit has ~240).
  const ptau0 = path.join(OUT, "pot10_0.ptau");
  const ptau1 = path.join(OUT, "pot10_1.ptau");
  const ptau = path.join(OUT, "pot10_final.ptau");
  await snarkjs.powersOfTau.newAccumulator(await bn128(), 10, ptau0);
  await snarkjs.powersOfTau.contribute(ptau0, ptau1, "manish-1", entropy());
  await snarkjs.powersOfTau.preparePhase2(ptau1, ptau);
  fs.rmSync(ptau0); fs.rmSync(ptau1);

  for (const c of CIRCUITS) {
    // Compile the circuit to constraints (r1cs) + a witness generator (wasm).
    // (circom2 runs as WebAssembly and only sees the current folder, so use relative paths.)
    execFileSync(path.join(ROOT, "node_modules/.bin/circom2"),
      ["circuits/" + c.file + ".circom", "--r1cs", "--wasm", "-o", "zk"], { cwd: ROOT, stdio: "inherit" });
    const r1cs = path.join(OUT, c.file + ".r1cs");
    const z0 = path.join(OUT, c.file + "_0.zkey");
    const zkey = path.join(OUT, c.file + ".zkey");
    // Phase 2: circuit-specific keys.
    await snarkjs.zKey.newZKey(r1cs, ptau, z0);
    await snarkjs.zKey.contribute(z0, zkey, "manish-2", entropy());
    fs.rmSync(z0);
    const vkey = await snarkjs.zKey.exportVerificationKey(zkey);
    fs.writeFileSync(path.join(OUT, c.file + ".vkey.json"), JSON.stringify(vkey, null, 2));
    // Solidity verifier generated from the verification key.
    const templates = { groth16: fs.readFileSync(path.join(ROOT, "node_modules/snarkjs/templates/verifier_groth16.sol.ejs"), "utf8") };
    let sol = await snarkjs.zKey.exportSolidityVerifier(zkey, templates);
    sol = sol.replace("contract Groth16Verifier", "contract " + c.contract)
      .replace(/pragma solidity [^;]+;/, "pragma solidity 0.8.24;");
    sol = sol.replace(/^(\/\/ SPDX[^\n]*\n)/, "$1// AUTO-GENERATED by scripts/zk-setup.js from zk/" + c.file + ".zkey (snarkjs). Do not edit.\n");
    fs.writeFileSync(path.join(ROOT, "contracts/verifiers", c.contract + ".sol"), sol);
    // Copy the witness generator next to the keys and drop circom's helper folder.
    fs.copyFileSync(path.join(OUT, c.file + "_js", c.file + ".wasm"), path.join(OUT, c.file + ".wasm"));
    fs.rmSync(path.join(OUT, c.file + "_js"), { recursive: true });
    console.log("✓", c.file, "→ zk/" + c.file + ".zkey, contracts/verifiers/" + c.contract + ".sol");
  }
  fs.rmSync(ptau); // only needed during setup
}

async function bn128() {
  return snarkjs.curves.getCurveFromName("bn128");
}

main().then(() => process.exit(0), (e) => { console.error(e); process.exit(1); });
